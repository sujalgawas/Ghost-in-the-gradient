import { BenchmarkData, BenchmarkSample, ModelMetrics } from '@/types/benchmark';
import fallbackData from '@/public/data/fieldbench_benchmark_results.json';
import { tryParseJSON } from './scoring';

let cachedBenchmarkData: BenchmarkData | null = null;

/**
 * Transforms any Hugging Face dataset URL into a direct raw JSON download URL.
 * Handles:
 * - https://huggingface.co/datasets/user/repo/blob/main/file.json -> /raw/main/file.json
 * - https://huggingface.co/datasets/user/repo -> /raw/main/fieldbench_benchmark_results.json
 */
export function sanitizeBenchmarkUrl(inputUrl?: string | null): string | null {
  if (!inputUrl || typeof inputUrl !== 'string') return null;
  let url = inputUrl.trim();
  if (!url) return null;

  // Replace /blob/ with /raw/ for direct raw content on Hugging Face
  if (url.includes('huggingface.co/') && url.includes('/blob/')) {
    url = url.replace('/blob/', '/raw/');
  }

  // If the user supplied the dataset root without the filename, append /raw/main/fieldbench_benchmark_results.json
  if (url.includes('huggingface.co/datasets/') && !url.endsWith('.json')) {
    url = url.replace(/\/+$/, '') + '/raw/main/fieldbench_benchmark_results.json';
  }

  return url;
}

function normalizePercent(val: any): number {
  if (val === undefined || val === null || isNaN(Number(val))) return 0;
  const num = Number(val);
  // If value is a ratio between 0 and 1, convert to percentage (e.g., 0.7375 -> 73.8)
  if (num > 0 && num <= 1) {
    return Math.round(num * 1000) / 10;
  }
  return Math.round(num * 10) / 10;
}

function formatDomainLabel(domain: string): string {
  const map: Record<string, string> = {
    clinical: 'Clinical Notes',
    contract: 'Legal Contracts',
    invoice: 'Financial Invoices',
    resume: 'Resumes / HR',
    support_ticket: 'Support Tickets',
  };
  return map[domain.toLowerCase()] || domain.charAt(0).toUpperCase() + domain.slice(1).replace(/_/g, ' ');
}

/**
 * Normalizes benchmark JSON whether it's generated by fieldbench_3model_benchmark.ipynb
 * (with summary_table, metadata, by_domain[sys][domain]) or pre-structured.
 */
export function normalizeBenchmarkData(raw: any): BenchmarkData {
  if (!raw || typeof raw !== 'object') {
    throw new Error('Invalid benchmark payload');
  }

  // 1. Overall Metrics
  let overall: { base: ModelMetrics; sftv2: ModelMetrics; dpo: ModelMetrics } = {
    base: { parse_ok: 0, schema_valid: 0, field_f1: 0, doc_exact: 0, null_acc: 0, hallucination_rate: 0, hallucination_rate_adj: 0 },
    sftv2: { parse_ok: 0, schema_valid: 0, field_f1: 0, doc_exact: 0, null_acc: 0, hallucination_rate: 0, hallucination_rate_adj: 0 },
    dpo: { parse_ok: 0, schema_valid: 0, field_f1: 0, doc_exact: 0, null_acc: 0, hallucination_rate: 0, hallucination_rate_adj: 0 },
  };

  if (raw.overall && raw.overall.base) {
    // Already structured
    overall = {
      base: {
        parse_ok: normalizePercent(raw.overall.base.parse_ok),
        schema_valid: normalizePercent(raw.overall.base.schema_valid),
        field_f1: normalizePercent(raw.overall.base.field_f1),
        doc_exact: normalizePercent(raw.overall.base.doc_exact),
        null_acc: normalizePercent(raw.overall.base.null_acc),
        hallucination_rate: normalizePercent(raw.overall.base.hallucination_rate),
        hallucination_rate_adj: normalizePercent(raw.overall.base.hallucination_rate_adj),
      },
      sftv2: {
        parse_ok: normalizePercent(raw.overall.sftv2?.parse_ok),
        schema_valid: normalizePercent(raw.overall.sftv2?.schema_valid),
        field_f1: normalizePercent(raw.overall.sftv2?.field_f1),
        doc_exact: normalizePercent(raw.overall.sftv2?.doc_exact),
        null_acc: normalizePercent(raw.overall.sftv2?.null_acc),
        hallucination_rate: normalizePercent(raw.overall.sftv2?.hallucination_rate),
        hallucination_rate_adj: normalizePercent(raw.overall.sftv2?.hallucination_rate_adj),
      },
      dpo: {
        parse_ok: normalizePercent(raw.overall.dpo?.parse_ok),
        schema_valid: normalizePercent(raw.overall.dpo?.schema_valid),
        field_f1: normalizePercent(raw.overall.dpo?.field_f1),
        doc_exact: normalizePercent(raw.overall.dpo?.doc_exact),
        null_acc: normalizePercent(raw.overall.dpo?.null_acc),
        hallucination_rate: normalizePercent(raw.overall.dpo?.hallucination_rate),
        hallucination_rate_adj: normalizePercent(raw.overall.dpo?.hallucination_rate_adj),
      },
    };
  } else if (Array.isArray(raw.summary_table)) {
    // From fieldbench_3model_benchmark.ipynb
    for (const row of raw.summary_table) {
      const sys = (row.system || '').toLowerCase() as 'base' | 'sftv2' | 'dpo';
      if (sys === 'base' || sys === 'sftv2' || sys === 'dpo') {
        overall[sys] = {
          parse_ok: normalizePercent(row.parse_ok),
          schema_valid: normalizePercent(row.schema_valid),
          field_f1: normalizePercent(row.field_f1),
          doc_exact: normalizePercent(row.doc_exact),
          null_acc: normalizePercent(row.null_acc),
          hallucination_rate: normalizePercent(row.hallucination_rate),
          hallucination_rate_adj: normalizePercent(row.hallucination_rate_adj),
        };
      }
    }
  }

  // 2. By Domain Breakdown
  const by_domain: Record<string, { base: ModelMetrics; sftv2: ModelMetrics; dpo: ModelMetrics }> = {};

  if (raw.by_domain && raw.by_domain.base && typeof raw.by_domain.base === 'object') {
    // Structure: raw.by_domain[system][domain]
    const domains = Object.keys(raw.by_domain.base);
    for (const dom of domains) {
      const label = formatDomainLabel(dom);
      by_domain[label] = {
        base: {
          parse_ok: normalizePercent(raw.by_domain.base[dom]?.parse_ok),
          schema_valid: normalizePercent(raw.by_domain.base[dom]?.schema_valid),
          field_f1: normalizePercent(raw.by_domain.base[dom]?.field_f1),
          doc_exact: normalizePercent(raw.by_domain.base[dom]?.doc_exact),
          null_acc: normalizePercent(raw.by_domain.base[dom]?.null_acc),
          hallucination_rate: normalizePercent(raw.by_domain.base[dom]?.hallucination_rate),
          hallucination_rate_adj: normalizePercent(raw.by_domain.base[dom]?.hallucination_rate_adj),
        },
        sftv2: {
          parse_ok: normalizePercent(raw.by_domain.sftv2?.[dom]?.parse_ok),
          schema_valid: normalizePercent(raw.by_domain.sftv2?.[dom]?.schema_valid),
          field_f1: normalizePercent(raw.by_domain.sftv2?.[dom]?.field_f1),
          doc_exact: normalizePercent(raw.by_domain.sftv2?.[dom]?.doc_exact),
          null_acc: normalizePercent(raw.by_domain.sftv2?.[dom]?.null_acc),
          hallucination_rate: normalizePercent(raw.by_domain.sftv2?.[dom]?.hallucination_rate),
          hallucination_rate_adj: normalizePercent(raw.by_domain.sftv2?.[dom]?.hallucination_rate_adj),
        },
        dpo: {
          parse_ok: normalizePercent(raw.by_domain.dpo?.[dom]?.parse_ok),
          schema_valid: normalizePercent(raw.by_domain.dpo?.[dom]?.schema_valid),
          field_f1: normalizePercent(raw.by_domain.dpo?.[dom]?.field_f1),
          doc_exact: normalizePercent(raw.by_domain.dpo?.[dom]?.doc_exact),
          null_acc: normalizePercent(raw.by_domain.dpo?.[dom]?.null_acc),
          hallucination_rate: normalizePercent(raw.by_domain.dpo?.[dom]?.hallucination_rate),
          hallucination_rate_adj: normalizePercent(raw.by_domain.dpo?.[dom]?.hallucination_rate_adj),
        },
      };
    }
  } else if (raw.by_domain) {
    // Structure: raw.by_domain[domain][system]
    for (const dom of Object.keys(raw.by_domain)) {
      const entry = raw.by_domain[dom];
      by_domain[formatDomainLabel(dom)] = {
        base: {
          parse_ok: normalizePercent(entry.base?.parse_ok),
          schema_valid: normalizePercent(entry.base?.schema_valid),
          field_f1: normalizePercent(entry.base?.field_f1),
          doc_exact: normalizePercent(entry.base?.doc_exact),
          null_acc: normalizePercent(entry.base?.null_acc),
          hallucination_rate: normalizePercent(entry.base?.hallucination_rate),
          hallucination_rate_adj: normalizePercent(entry.base?.hallucination_rate_adj),
        },
        sftv2: {
          parse_ok: normalizePercent(entry.sftv2?.parse_ok),
          schema_valid: normalizePercent(entry.sftv2?.schema_valid),
          field_f1: normalizePercent(entry.sftv2?.field_f1),
          doc_exact: normalizePercent(entry.sftv2?.doc_exact),
          null_acc: normalizePercent(entry.sftv2?.null_acc),
          hallucination_rate: normalizePercent(entry.sftv2?.hallucination_rate),
          hallucination_rate_adj: normalizePercent(entry.sftv2?.hallucination_rate_adj),
        },
        dpo: {
          parse_ok: normalizePercent(entry.dpo?.parse_ok),
          schema_valid: normalizePercent(entry.dpo?.schema_valid),
          field_f1: normalizePercent(entry.dpo?.field_f1),
          doc_exact: normalizePercent(entry.dpo?.doc_exact),
          null_acc: normalizePercent(entry.dpo?.null_acc),
          hallucination_rate: normalizePercent(entry.dpo?.hallucination_rate),
          hallucination_rate_adj: normalizePercent(entry.dpo?.hallucination_rate_adj),
        },
      };
    }
  }

  // 3. Samples
  const samples: BenchmarkSample[] = (raw.samples || []).map((s: any, idx: number) => {
    const rawDomain = s.domain || 'general';
    const domainLabel = formatDomainLabel(rawDomain);
    const id = s.id || `sample_${idx + 1}`;
    const title = s.title || `${domainLabel} Document (${id})`;

    const formatPrediction = (pred: any) => {
      if (!pred) {
        return {
          raw_output: '',
          parsed_json: null,
          parse_ok: false,
          schema_valid: false,
          latency_ms: 0,
        };
      }

      const rawOutput = pred.raw_output || '';
      let parsed = pred.parsed_json;
      if (parsed === undefined || parsed === null) {
        const attempt = tryParseJSON(rawOutput);
        parsed = attempt.ok ? attempt.parsed : null;
      }

      const scores = pred.scores || {};
      const parseOk = pred.parse_ok !== undefined ? Boolean(pred.parse_ok) : Boolean(scores.parse_ok);
      const schemaValid = pred.schema_valid !== undefined ? Boolean(pred.schema_valid) : Boolean(scores.schema_valid);
      const docExact = pred.doc_exact !== undefined ? Boolean(pred.doc_exact) : Boolean(scores.doc_exact);
      const fieldF1Val = normalizePercent(pred.field_f1 ?? scores.field_f1 ?? 0);

      return {
        raw_output: rawOutput,
        parsed_json: parsed,
        parse_ok: parseOk,
        schema_valid: schemaValid,
        latency_ms: Math.round(pred.latency_ms || 0),
        doc_exact: docExact,
        field_f1: fieldF1Val,
      };
    };

    return {
      id,
      domain: domainLabel,
      title,
      document: s.document || '',
      schema: s.schema || { type: 'object' },
      gold: s.gold || {},
      predictions: {
        base: formatPrediction(s.predictions?.base),
        sftv2: formatPrediction(s.predictions?.sftv2),
        dpo: formatPrediction(s.predictions?.dpo),
      },
    };
  });

  return {
    benchmark_name: raw.benchmark_name || raw.metadata?.benchmark || 'FieldBench: Tiny-Aya Schema-Conditioned JSON Evaluation',
    description: raw.description || `Evaluated on ${samples.length} real document samples across ${Object.keys(by_domain).length} domains.`,
    timestamp: raw.timestamp || raw.metadata?.generated_at_utc || new Date().toISOString(),
    models: {
      base: {
        name: raw.models?.base?.name || raw.metadata?.models?.base?.label || 'Base (Tiny-Aya-Global)',
        repo_id: raw.models?.base?.repo_id || raw.metadata?.models?.base?.base_model || 'CohereLabs/tiny-aya-global',
        description: 'Vanilla 3.35B pre-trained foundation model.',
      },
      sftv2: {
        name: raw.models?.sftv2?.name || raw.metadata?.models?.sftv2?.label || 'SFT v2 Adapter',
        repo_id: raw.models?.sftv2?.repo_id || raw.metadata?.models?.sftv2?.adapter_repo || 'monson2002/tiny-aya-sft-v2-adapter',
        description: 'Supervised fine-tuned LoRA adapter on schema-constrained JSON extraction.',
      },
      dpo: {
        name: raw.models?.dpo?.name || raw.metadata?.models?.dpo?.label || 'DPO Aligned Adapter',
        repo_id: raw.models?.dpo?.repo_id || raw.metadata?.models?.dpo?.adapter_repo || 'monson2002/tiny-aya-sft-v2-dpo-adapter',
        description: 'Direct Preference Optimization aligned adapter.',
      },
    },
    overall,
    by_domain,
    samples,
  };
}

export async function loadBenchmarkData(): Promise<BenchmarkData> {
  const remoteUrl = sanitizeBenchmarkUrl(process.env.NEXT_PUBLIC_BENCHMARK_JSON_URL);

  if (remoteUrl) {
    try {
      const res = await fetch(remoteUrl, { next: { revalidate: 300 } });
      if (res.ok) {
        const json = await res.json();
        cachedBenchmarkData = normalizeBenchmarkData(json);
        return cachedBenchmarkData;
      } else {
        console.warn(`Remote benchmark fetch returned HTTP ${res.status} from ${remoteUrl}`);
      }
    } catch (err) {
      console.warn('Failed to fetch remote benchmark JSON, falling back to local dataset:', err);
    }
  }

  // Fallback to local static JSON (which now contains the user's real 80-sample dataset)
  cachedBenchmarkData = normalizeBenchmarkData(fallbackData);
  return cachedBenchmarkData;
}
